function getSettings() {
    try {
        return {
            currency: localStorage.getItem('corebiq-currency') || 'INR',
            country: localStorage.getItem('corebiq-country') || 'IN',
            language: localStorage.getItem('corebiq-language') || 'en'
        };
    } catch (error) {
        console.warn('Unable to read saved locale settings:', error);
        return { currency: 'INR', country: 'IN', language: 'en' };
    }
}

function getLocale(language = getSettings().language, country = getSettings().country) {
    const languageTag = { en: 'en', fr: 'fr', ar: 'ar' }[language] || 'en';
    const region = country && /^[A-Z]{2}$/.test(country) ? country : 'IN';
    try {
        return new Intl.Locale(languageTag, { region }).toString();
    } catch {
        return languageTag === 'en' ? 'en-IN' : languageTag === 'fr' ? 'fr-FR' : 'ar';
    }
    window.corebiqLocale = getLocale;
}

function currencyParts() {
    const { currency } = getSettings();
    try {
        return new Intl.NumberFormat(getLocale(), { style: 'currency', currency }).formatToParts(0);
    } catch (error) {
        console.error('Invalid company currency setting:', error);
        return new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR' }).formatToParts(0);
    }
}

window.formatCorebiqCurrency = function(value, options = {}) {
    const { currency } = getSettings();
    try {
        const formatOptions = { style: 'currency', currency, ...options };
        return new Intl.NumberFormat(getLocale(), formatOptions).format(Number(value) || 0);
    } catch (error) {
        console.error('Unable to format currency:', error);
        return new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR' }).format(Number(value) || 0);
    }
};

window.formatCorebiqNumber = function(value, options = {}) {
    return new Intl.NumberFormat(getLocale(), {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2,
        ...options
    }).format(Number(value) || 0);
};

function translateText(value, language) {
    if (language === 'en') return value;
    const dictionary = phraseTranslations[language];
    if (!dictionary) return value;
    const normalized = value.trim().replace(/\s+/g, ' ').toLowerCase();
    if (dictionary[normalized]) {
        const leading = value.match(/^\s*/)?.[0] || '';
        const trailing = value.match(/\s*$/)?.[0] || '';
        return `${leading}${dictionary[normalized]}${trailing}`;
    }
    const words = wordTranslations[language];
    return value.replace(/[\p{L}\p{M}]+/gu, word => words[word.toLowerCase()] || word);
}

