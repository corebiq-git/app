const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const skippedText = 'script,style,noscript,textarea,input,select,option,[contenteditable="true"],[data-no-translate],.material-symbols-rounded,.patient-name,.patient-info,.ledger-row td';
let observer;
let scheduled = false;

function getSettings() {
    return {
        currency: localStorage.getItem('corebiq-currency') || 'INR',
        country: localStorage.getItem('corebiq-country') || 'IN',
        language: localStorage.getItem('corebiq-language') || 'en'
    };
}

function getLocale(language = getSettings().language, country = getSettings().country) {
    const languageTag = { en: 'en', fr: 'fr', ar: 'ar' }[language] || 'en';
    const region = country && /^[A-Z]{2}$/.test(country) ? country : 'IN';
    try {
        return new Intl.Locale(languageTag, { region }).toString();
    } catch {
        return languageTag === 'en' ? 'en-IN' : languageTag === 'fr' ? 'fr-FR' : 'ar';
    }
}

function currencyParts() {
    const { currency } = getSettings();
    try {
        return new Intl.NumberFormat(getLocale(), { style: 'currency', currency }).formatToParts(0);
    } catch (error) {
        console.error('Invalid company currency setting:', error);
        return new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR' }).formatToParts(0);
    }
}

window.formatCorebiqCurrency = function(value, options = {}) {
    const { currency } = getSettings();
    try {
        const formatOptions = { style: 'currency', currency, ...options };
        return new Intl.NumberFormat(getLocale(), formatOptions).format(Number(value) || 0);
    } catch (error) {
        console.error('Unable to format currency:', error);
        return new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR' }).format(Number(value) || 0);
    }
};

function translateText(value, language) {
    if (language === 'en') return value;
    const dictionary = phraseTranslations[language];
    const normalized = value.trim().replace(/\s+/g, ' ').toLowerCase();
    if (dictionary[normalized]) {
        const leading = value.match(/^\s*/)?.[0] || '';
        const trailing = value.match(/\s*$/)?.[0] || '';
        return `${leading}${dictionary[normalized]}${trailing}`;
    }
    const words = wordTranslations[language];
    return value.replace(/[\p{L}\p{M}]+/gu, word => words[word.toLowerCase()] || word);
}

function shouldSkipTextNode(node) {
    const parent = node.parentElement;
    return !parent || Boolean(parent.closest(skippedText)) ||
        Boolean(parent.closest('tbody') && !parent.closest('button,a'));
}

function formatCurrencyText(value, language) {
    const symbol = currencyParts().filter(part => part.type === 'currency').map(part => part.value).join('');
    const amountPattern = /₹\s*(-?\d[\d,]*(?:\.\d+)?)/g;
    return value
        .replace(amountPattern, (_, amount) => {
            const numericValue = Number(amount.replace(/,/g, ''));
            return Number.isFinite(numericValue) ? window.formatCorebiqCurrency(numericValue) : `₹${amount}`;
        })
        .replace(/₹/g, symbol);
}

function localizeNode(node, language) {
    if (node.nodeType === Node.TEXT_NODE) {
        if (shouldSkipTextNode(node)) return;
        if (!originalText.has(node)) originalText.set(node, node.nodeValue);
        const source = originalText.get(node);
        const localized = formatCurrencyText(translateText(source, language), language);
        if (node.nodeValue !== localized) node.nodeValue = localized;
        return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
    if (node.nodeType === Node.ELEMENT_NODE && node.matches(skippedText)) return;

    if (node.nodeType === Node.ELEMENT_NODE) {
        let attributes = originalAttributes.get(node);
        if (!attributes) {
            attributes = new Map();
            originalAttributes.set(node, attributes);
        }
        ['aria-label', 'placeholder', 'title'].forEach(attribute => {
            if (!node.hasAttribute(attribute)) return;
            if (!attributes.has(attribute)) attributes.set(attribute, node.getAttribute(attribute));
            const source = attributes.get(attribute);
            const localized = translateText(source, language).replace(/₹/g, currencyParts().find(part => part.type === 'currency')?.value || '₹');
            if (node.getAttribute(attribute) !== localized) node.setAttribute(attribute, localized);
        });
    }
    node.childNodes.forEach(child => localizeNode(child, language));
}

window.applyCorebiqSettings = function(settings = {}) {
    const currency = String(settings.currencyCode || settings.currency || 'INR').toUpperCase();
    const country = String(settings.countryCode || settings.country || 'IN').toUpperCase();
    const language = ['en', 'ar', 'fr'].includes(String(settings.preferredLanguage || settings.language || 'en').toLowerCase())
        ? String(settings.preferredLanguage || settings.language || 'en').toLowerCase()
        : 'en';
    localStorage.setItem('corebiq-currency', currency);
    localStorage.setItem('corebiq-country', country);
    localStorage.setItem('corebiq-language', language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    if (document.body) document.body.dir = language === 'ar' ? 'rtl' : 'ltr';
    localizeNode(document.body || document.documentElement, language);
    window.dispatchEvent(new CustomEvent('corebiq:settings-changed', { detail: { currency, country, language } }));
};

function scheduleLocalization() {
    if (scheduled) return;
    scheduled = true;
    queueMicrotask(() => {
        scheduled = false;
        localizeNode(document.body || document.documentElement, getSettings().language);
    });
}

if (typeof document !== 'undefined') {
    const settings = getSettings();
    document.documentElement.lang = settings.language;
    document.documentElement.dir = settings.language === 'ar' ? 'rtl' : 'ltr';
    if (document.body) document.body.dir = settings.language === 'ar' ? 'rtl' : 'ltr';
    observer = new MutationObserver(scheduleLocalization);
    observer.observe(document.documentElement, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['aria-label', 'placeholder', 'title'] });
    scheduleLocalization();
}
